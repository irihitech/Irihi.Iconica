                sb.AppendLine($"            Transform = {CreateMatrix(ellipseData.Transform)},");
            sb.AppendLine("        },");
        }
        else if (element is LineDrawingElement lineData)
        {
            sb.AppendLine("        new LineDrawingElement()");
            sb.AppendLine("        {");
            sb.AppendLine($"            X1 = {lineData.X1},");
            sb.AppendLine($"            Y1 = {lineData.Y1},");
            sb.AppendLine($"            X2 = {lineData.X2},");
            sb.AppendLine($"            Y2 = {lineData.Y2},");
            sb.AppendLine($"            StrokeIndex = {lineData.StrokeIndex},");
            if (lineData.FillIndex >= 0) sb.AppendLine($"            FillIndex = {lineData.FillIndex},");
            sb.AppendLine($"            InheritStrokeWidth = {lineData.InheritStrokeWidth.ToString().ToLower()},");
