                sb.AppendLine($"            Transform = {CreateMatrix(lineData.Transform)},");
            sb.AppendLine("        },");
        }
        else if (element is RectDrawingElement rectData)
        {
            sb.AppendLine("        new RectDrawingElement()");
            sb.AppendLine("        {");
            sb.AppendLine($"            Width = {rectData.Width},");
            sb.AppendLine($"            Height = {rectData.Height},");
